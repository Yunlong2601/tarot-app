// Regenerates src/cards.ts from the app's cards.json so the server maps card
// IDs to names itself (the client can never inject card text).
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../app/assets/cards/cards.json", import.meta.url);
const cards = JSON.parse(readFileSync(src, "utf8")).cards;
if (cards.length !== 78) throw new Error(`expected 78 cards, got ${cards.length}`);

const rows = cards.map(
  (c) => `  ${JSON.stringify(c.id)}: { name: ${JSON.stringify(c.name)}, keywords: ${JSON.stringify(c.keywords)} },`,
);
writeFileSync(
  new URL("../src/cards.ts", import.meta.url),
  `// GENERATED by scripts/gen-cards.mjs from app/assets/cards/cards.json. Do not edit.\n` +
    `export interface CardInfo { name: string; keywords: string[] }\n\n` +
    `export const CARDS: Record<string, CardInfo> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`wrote ${cards.length} cards`);
