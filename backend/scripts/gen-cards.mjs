// Regenerates src/cards.ts from the app's card files so the server maps card
// IDs to names and meanings itself (the client can never inject card text).
//   app/assets/cards/cards.json      all 78 cards, short meanings
//   app/assets/cards/knowledge.json  richer, original knowledge (22 majors so far)
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), "utf8"));
const cards = read("../../app/assets/cards/cards.json").cards;
const know = read("../../app/assets/cards/knowledge.json").cards;
if (cards.length !== 78) throw new Error(`expected 78 cards, got ${cards.length}`);

const rows = cards.map((c) => {
  const o = {
    name: c.name,
    arcana: c.arcana,
    suit: c.suit ?? null,
    number: c.number ?? null,
    element: c.element ?? null,
    association: c.association ?? null,
    keywords: c.keywords,
    upright: c.upright,
    reversed: c.reversed,
  };
  if (know[c.id]) o.k = know[c.id];
  return `  ${JSON.stringify(c.id)}: ${JSON.stringify(o)},`;
});

writeFileSync(
  new URL("../src/cards.ts", import.meta.url),
  `// GENERATED by scripts/gen-cards.mjs from app/assets/cards/*.json. Do not edit.\n` +
    `export interface CardKnowledge {\n` +
    `  essence: string; imagery: string; why: string;\n` +
    `  upright: { core: string; light: string; shadow: string; love: string; work: string; question: string };\n` +
    `  reversed: { core: string; modes: string[]; question: string };\n` +
    `}\n` +
    `export interface CardInfo {\n` +
    `  name: string; arcana: "major" | "minor"; suit: string | null; number: number | null;\n` +
    `  element: string | null; association: string | null; keywords: string[];\n` +
    `  upright: string; reversed: string; k?: CardKnowledge;\n` +
    `}\n\n` +
    `export const CARDS: Record<string, CardInfo> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`wrote ${cards.length} cards, ${Object.keys(know).length} with rich knowledge`);
